#!/usr/bin/env node
/**
 * Emits stable RS256 AUTH_JWT_* lines for local dev (.env.local).
 * @see docs/phase-9/appendices/IDENTITY-PORT-SCOPE.md § Dev JWT bootstrap
 */
import { exportPKCS8, exportSPKI, generateKeyPair } from "jose";

function pemToEnvLine(name, pem) {
  const escaped = pem.replace(/\r?\n/g, "\\n");
  return `${name}="${escaped}"`;
}

const pair = await generateKeyPair("RS256", { extractable: true });
const publicKey = await exportSPKI(pair.publicKey);
const privateKey = await exportPKCS8(pair.privateKey);

console.log("# Generated by apps/api/scripts/bootstrap-dev-jwt-keys.mjs — append to apps/api/.env.local");
console.log(pemToEnvLine("AUTH_JWT_PUBLIC_KEY", publicKey));
console.log(pemToEnvLine("AUTH_JWT_PRIVATE_KEY", privateKey));
console.log('AUTH_JWT_ISSUER="tour-ops"');
console.log('AUTH_JWT_AUDIENCE="tour-ops-api"');
