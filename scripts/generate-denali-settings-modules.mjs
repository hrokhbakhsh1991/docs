#!/usr/bin/env node
/**
 * Emits Denali backend-required settings module ids for web consistency guard.
 * Run: pnpm run generate:denali-settings-modules
 * Check: pnpm run generate:denali-settings-modules --check
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const REPO_ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const MANIFEST_PATH = join(
  REPO_ROOT,
  "packages/workspaces/denali/src/settings/denali-settings.manifest.ts",
);
const OUTPUT_PATH = join(
  REPO_ROOT,
  "apps/web/src/features/settings/denali-required-settings-modules.generated.ts",
);

function extractDenaliSettingsModuleIds(manifestSource) {
  const match = manifestSource.match(
    /const DENALI_SETTINGS_MODULES = Object\.freeze\(\[([\s\S]*?)\]\s*as const/,
  );
  if (match === null) {
    throw new Error(`${MANIFEST_PATH}: DENALI_SETTINGS_MODULES block not found`);
  }
  const ids = [...match[1].matchAll(/\bid:\s*"([^"]+)"/g)].map((entry) => entry[1]);
  if (ids.length === 0) {
    throw new Error(`${MANIFEST_PATH}: no settings module ids extracted`);
  }
  return ids;
}

function buildGeneratedContent(moduleIds) {
  return `/**
 * AUTO-GENERATED by scripts/generate-denali-settings-modules.mjs — DO NOT EDIT.
 * Source: packages/workspaces/denali/src/settings/denali-settings.manifest.ts
 * Regenerate: pnpm run generate:denali-settings-modules
 */
export const DENALI_BACKEND_REQUIRED_MODULE_IDS = [
${moduleIds.map((id) => `  "${id}",`).join("\n")}
] as const;
`;
}

const moduleIds = extractDenaliSettingsModuleIds(readFileSync(MANIFEST_PATH, "utf8"));
const content = buildGeneratedContent(moduleIds);
const checkOnly = process.argv.includes("--check");

if (checkOnly) {
  const existing = readFileSync(OUTPUT_PATH, "utf8");
  if (existing !== content) {
    console.error("generate:denali-settings-modules --check: FAIL (stale generated file)");
    console.error("Run: pnpm run generate:denali-settings-modules");
    process.exit(1);
  }
  console.log(`generate:denali-settings-modules --check: PASS (${moduleIds.length} module ids)`);
} else {
  writeFileSync(OUTPUT_PATH, content, "utf8");
  console.log(`Wrote ${OUTPUT_PATH} (${moduleIds.length} module ids)`);
}
