#!/usr/bin/env bash
# Render /etc/caddy/caddy.env from both VPS app stacks (P10-1-N-001)
set -euo pipefail

PROD_ENV_DIR="${PROD_ENV_DIR:-/etc/app-tour}"
STAGING_ENV_DIR="${STAGING_ENV_DIR:-/etc/app-tour-staging}"
OUT="${CADDY_ENV_FILE:-/etc/caddy/caddy.env}"
PLATFORM_ROOT_DOMAIN="${PLATFORM_ROOT_DOMAIN:-}"

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=lib/ports.sh
source "${SCRIPT_DIR}/lib/ports.sh"
collect_app_ports "$PROD_ENV_DIR"
PROD_API_PORT="${API_PORT:-3001}"
PROD_WEB_PORT="${WEB_PORT:-3000}"
PROD_MARKETING_PORT="${MARKETING_PORT:-3002}"
PROD_PORTAL_PORT="${PORTAL_PORT:-3003}"
PRODUCTION_PORTS=("${APP_PORTS[@]}" "$PROD_API_PORT" "$PROD_WEB_PORT" "$PROD_MARKETING_PORT" "$PROD_PORTAL_PORT")

if [[ ! -d "$STAGING_ENV_DIR" ]]; then
  echo "[caddy-env] missing staging env directory" >&2
  exit 1
fi
for app in api web marketing portal; do
  if [[ ! -f "${STAGING_ENV_DIR}/${app}.env" ]]; then
    echo "[caddy-env] missing staging ${app}.env" >&2
    exit 1
  fi
done
STAGING_API_PORT="$(read_env_port "${STAGING_ENV_DIR}/api.env" PORT 23001)"
STAGING_WEB_PORT="$(read_env_port "${STAGING_ENV_DIR}/web.env" PORT 23000)"
STAGING_MARKETING_PORT="$(read_env_port "${STAGING_ENV_DIR}/marketing.env" PORT 23002)"
STAGING_PORTAL_PORT="$(read_env_port "${STAGING_ENV_DIR}/portal.env" PORT 23003)"

STAGING_PORTS=()
for port in "$STAGING_API_PORT" "$STAGING_WEB_PORT" "$STAGING_MARKETING_PORT" "$STAGING_PORTAL_PORT"; do
  if [[ ! "$port" =~ ^[0-9]{1,5}$ ]] || ((10#$port < 1 || 10#$port > 65535)); then
    echo "[caddy-env] invalid staging app port" >&2
    exit 1
  fi
  for production_port in "${PRODUCTION_PORTS[@]}"; do
    if [[ "$port" == "$production_port" ]]; then
      echo "[caddy-env] staging app port collides with production" >&2
      exit 1
    fi
  done
  for existing_port in "${STAGING_PORTS[@]}"; do
    if [[ "$port" == "$existing_port" ]]; then
      echo "[caddy-env] duplicate staging app port" >&2
      exit 1
    fi
  done
  STAGING_PORTS+=("$port")
done

if [[ -z "$PLATFORM_ROOT_DOMAIN" ]]; then
  PLATFORM_ROOT_DOMAIN="$(read_env_var "${PROD_ENV_DIR}/web.env" PLATFORM_ROOT_DOMAIN 2>/dev/null || true)"
fi
if [[ -z "$PLATFORM_ROOT_DOMAIN" ]]; then
  PLATFORM_ROOT_DOMAIN="$(read_env_var "${PROD_ENV_DIR}/api.env" PLATFORM_ROOT_DOMAIN 2>/dev/null || true)"
fi
PLATFORM_ROOT_DOMAIN="${PLATFORM_ROOT_DOMAIN:-staging.example.com}"
CANONICAL_TENANT_LABEL="${CANONICAL_TENANT_LABEL:-$(read_env_var "${PROD_ENV_DIR}/web.env" PUBLIC_TENANT_FALLBACK_LABEL 2>/dev/null || true)}"
CANONICAL_TENANT_LABEL="${CANONICAL_TENANT_LABEL:-denali}"
STAGING_SECOND_TENANT_LABEL="${STAGING_SECOND_TENANT_LABEL:-$(read_env_var "${STAGING_ENV_DIR}/web.env" STAGING_SECOND_TENANT_LABEL 2>/dev/null || true)}"
STAGING_SECOND_TENANT_LABEL="${STAGING_SECOND_TENANT_LABEL:-qa2}"
if [[ ! "$STAGING_SECOND_TENANT_LABEL" =~ ^[a-z0-9]+(-[a-z0-9]+)*$ ]] ||
  [[ "$STAGING_SECOND_TENANT_LABEL" == "$CANONICAL_TENANT_LABEL" ]]; then
  echo "[caddy-env] invalid staging second tenant label" >&2
  exit 1
fi
STAGING_SECOND_TENANT_ENABLED="${STAGING_SECOND_TENANT_ENABLED:-$(read_env_var "${STAGING_ENV_DIR}/web.env" STAGING_SECOND_TENANT_ENABLED 2>/dev/null || true)}"
STAGING_SECOND_TENANT_ENABLED="${STAGING_SECOND_TENANT_ENABLED:-false}"
if [[ "$STAGING_SECOND_TENANT_ENABLED" != "true" && "$STAGING_SECOND_TENANT_ENABLED" != "false" ]]; then
  echo "[caddy-env] STAGING_SECOND_TENANT_ENABLED must be true or false" >&2
  exit 1
fi
MINIO_PUBLIC_HOST="$(read_env_var "${PROD_ENV_DIR}/api.env" MINIO_PUBLIC_HOST 2>/dev/null || true)"
MINIO_PUBLIC_HOST="${MINIO_PUBLIC_HOST:-storage.${CANONICAL_TENANT_LABEL}.${PLATFORM_ROOT_DOMAIN}}"
MINIO_PORT="${MINIO_PORT:-9002}"
PORTAL_PUBLIC_BASE_URL="$(read_env_var "${PROD_ENV_DIR}/portal.env" PORTAL_PUBLIC_BASE_URL 2>/dev/null || true)"
PORTAL_PUBLIC_BASE_URL="${PORTAL_PUBLIC_BASE_URL:-$(read_env_var "${PROD_ENV_DIR}/marketing.env" PORTAL_PUBLIC_BASE_URL 2>/dev/null || true)}"
# Env files may use shell-style double quotes around URL values.
PORTAL_PUBLIC_BASE_URL="$(printf '%s' "$PORTAL_PUBLIC_BASE_URL" | sed -E 's/^"//; s/"$//')"
CANONICAL_PORTAL_HOST="${CANONICAL_PORTAL_HOST:-}"
if [[ -z "$CANONICAL_PORTAL_HOST" && -n "$PORTAL_PUBLIC_BASE_URL" ]]; then
  CANONICAL_PORTAL_HOST="$(printf '%s' "$PORTAL_PUBLIC_BASE_URL" | sed -E 's#^[[:alpha:]][[:alnum:].+-]*://([^/:]+)(:[0-9]+)?(/.*)?$#\1#')"
fi
CANONICAL_PORTAL_HOST="${CANONICAL_PORTAL_HOST:-portal.${CANONICAL_TENANT_LABEL}.${PLATFORM_ROOT_DOMAIN}}"
[[ "$CANONICAL_PORTAL_HOST" =~ ^[A-Za-z0-9.-]+$ ]] || {
  echo "[caddy-env] invalid canonical portal host: $CANONICAL_PORTAL_HOST" >&2
  exit 1
}
[[ "$MINIO_PUBLIC_HOST" =~ ^[A-Za-z0-9.-]+$ ]] || {
  echo "[caddy-env] invalid public MinIO host: $MINIO_PUBLIC_HOST" >&2
  exit 1
}

mkdir -p "$(dirname "$OUT")"
cat >"$OUT" <<EOF
# Generated by render-caddy-env.sh — do not edit by hand
PLATFORM_ROOT_DOMAIN=${PLATFORM_ROOT_DOMAIN}
CANONICAL_TENANT_LABEL=${CANONICAL_TENANT_LABEL}
STAGING_SECOND_TENANT_LABEL=${STAGING_SECOND_TENANT_LABEL}
STAGING_SECOND_TENANT_ENABLED=${STAGING_SECOND_TENANT_ENABLED}
CANONICAL_PORTAL_HOST=${CANONICAL_PORTAL_HOST}
MINIO_PUBLIC_HOST=${MINIO_PUBLIC_HOST}
MINIO_PORT=${MINIO_PORT}
PROD_API_PORT=${PROD_API_PORT}
PROD_WEB_PORT=${PROD_WEB_PORT}
PROD_MARKETING_PORT=${PROD_MARKETING_PORT}
PROD_PORTAL_PORT=${PROD_PORTAL_PORT}
STAGING_API_PORT=${STAGING_API_PORT}
STAGING_WEB_PORT=${STAGING_WEB_PORT}
STAGING_MARKETING_PORT=${STAGING_MARKETING_PORT}
STAGING_PORTAL_PORT=${STAGING_PORTAL_PORT}
# Backward-compatible aliases for diagnostics; Caddy routes use the explicit
# PROD_* and STAGING_* variables above.
API_PORT=${PROD_API_PORT}
WEB_PORT=${PROD_WEB_PORT}
MARKETING_PORT=${PROD_MARKETING_PORT}
PORTAL_PORT=${PROD_PORTAL_PORT}
CADDY_ACME_EMAIL=${CADDY_ACME_EMAIL:-ops@example.com}
EOF

chmod 640 "$OUT"
echo "[caddy-env] wrote $OUT (prod=${PROD_WEB_PORT}/${PROD_API_PORT}/${PROD_MARKETING_PORT}/${PROD_PORTAL_PORT} staging=${STAGING_WEB_PORT}/${STAGING_API_PORT}/${STAGING_MARKETING_PORT}/${STAGING_PORTAL_PORT} second-tenant=${STAGING_SECOND_TENANT_LABEL}/${STAGING_SECOND_TENANT_ENABLED})"
