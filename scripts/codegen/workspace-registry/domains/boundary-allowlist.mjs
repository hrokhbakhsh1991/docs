/**
 * Full `from.pathNot` body for apps-api-workspace-plugin-registry-only (parentheses included).
 * Preserves historical fragment order: product tokens sit between platform neighbors.
 */
export function buildDepcruiseApiPluginRegistryFromPathNot() {
  const fragments = [
    "workspace-plugin-registry\\.generated",
    "workspace-tour-write-bindings\\.generated",
    "\\.generated\\.ts$",
    "\\.spec\\.ts$",
    "denali-finance",
    "workspace-finance",
    "urban",
    "canonical",
    "internal/provisioning",
    "settings/",
    "tours/",
    "tenant/tenant-branding-storage",
  ];
  return `(${fragments.join("|")})`;
}

const CJS_BANNER = `/**
 * AUTO-GENERATED by scripts/generate-workspace-registry.mjs — DO NOT EDIT.
 * Source: workspace.manifest.json per workspace package.
 * Regenerate: pnpm run generate:workspace-registry
 * P5.2 / P5.2.b / P5.2.c / P5.4 — web+API depcruise + guest-consumer-deps + generated-banner + frozen-shell.
 */
`;

/**
 * @param {ReturnType<typeof import("../manifest-loader.mjs").discoverManifests>} manifests
 */
export function generateManifestBoundaryAllowlist(manifests) {
  const all = manifests.slice().sort((a, b) => a.id.localeCompare(b.id));
  const product = productWorkspaceManifests(manifests)
    .slice()
    .sort((a, b) => a.id.localeCompare(b.id));
  const portal = selectPortalRegisterManifests(manifests);

  const productIds = product.map((m) => m.id);
  const productPackages = product.map((m) => m.package);
  const allIds = all.map((m) => m.id);
  const allPackages = all.map((m) => m.package);

  const webNegativeLookahead = productIds.map(escapeRegexLiteral).join("|");
  const webAllowAlt = productIds.map((id) => `workspaces/${escapeRegexLiteral(id)}`).join("|");
  const apiAllowAlt = allIds.map((id) => `workspaces/${escapeRegexLiteral(id)}`).join("|");
  const apiProductAlt = productIds.map(escapeRegexLiteral).join("|");
  const productIdAlt = productIds.map(escapeRegexLiteral).join("|");
  const apiPluginRegistryFromPathNot = buildDepcruiseApiPluginRegistryFromPathNot();

  const portalRegisterRels = portal.map(
    (m) => `packages/guest-workspace-runtime/src/register-${m.id}.generated.ts`
  );

  return `${CJS_BANNER}"use strict";

/** @type {readonly string[]} */
const PRODUCT_WORKSPACE_IDS = Object.freeze(${JSON.stringify(productIds, null, 2)});

/** @type {readonly string[]} */
const PRODUCT_WORKSPACE_PACKAGES = Object.freeze(${JSON.stringify(productPackages, null, 2)});

/** All discovered workspace ids (includes registryOnly finance/booking fixtures). */
/** @type {readonly string[]} */
const ALL_WORKSPACE_IDS = Object.freeze(${JSON.stringify(allIds, null, 2)});

/** @type {readonly string[]} */
const ALL_WORKSPACE_PACKAGES = Object.freeze(${JSON.stringify(allPackages, null, 2)});

/**
 * Alternation for \`packages/workspaces/(?!…)\` (apps-web-no-workspaces-except-starter).
 * @type {string}
 */
const DEPCRUISE_WEB_WORKSPACES_NEGATIVE_LOOKAHEAD = ${JSON.stringify(webNegativeLookahead)};

/**
 * Alternation for \`workspaces/<id>\` inside apps-web-allowed-packages negative package set.
 * @type {string}
 */
const DEPCRUISE_WEB_WORKSPACES_ALLOW_ALT = ${JSON.stringify(webAllowAlt)};

/**
 * Alternation for \`workspaces/<id>\` inside apps-api-allowed-packages (all manifests).
 * @type {string}
 */
const DEPCRUISE_API_WORKSPACES_ALLOW_ALT = ${JSON.stringify(apiAllowAlt)};

/**
 * Alternation for apps-api-workspace-plugin-registry-only \`to.path\` product dirs.
 * @type {string}
 */
const DEPCRUISE_API_PRODUCT_WORKSPACES_ALT = ${JSON.stringify(apiProductAlt)};

/**
 * Gap Closure P5.2.c — \`from.pathNot\` for apps-api-workspace-plugin-registry-only.
 * @type {string}
 */
const DEPCRUISE_API_PLUGIN_REGISTRY_FROM_PATH_NOT = ${JSON.stringify(apiPluginRegistryFromPathNot)};

/** @type {readonly string[]} */
const DEPCRUISE_API_PLUGIN_REGISTRY_PRODUCT_PATH_NOT_FRAGMENTS = Object.freeze(${JSON.stringify(
    [...DEPCRUISE_API_PLUGIN_REGISTRY_PRODUCT_PATH_NOT_FRAGMENTS],
    null,
    2
  )});

/**
 * Alternation for product workspace ids (guards scanning source for package imports).
 * @type {string}
 */
const PRODUCT_WORKSPACE_ID_ALT = ${JSON.stringify(productIdAlt)};

/** @type {readonly string[]} */
const PORTAL_REGISTER_GENERATED_RELS = Object.freeze(${JSON.stringify(portalRegisterRels, null, 2)});

module.exports = {
  PRODUCT_WORKSPACE_IDS,
  PRODUCT_WORKSPACE_PACKAGES,
  ALL_WORKSPACE_IDS,
  ALL_WORKSPACE_PACKAGES,
  DEPCRUISE_WEB_WORKSPACES_NEGATIVE_LOOKAHEAD,
  DEPCRUISE_WEB_WORKSPACES_ALLOW_ALT,
  DEPCRUISE_API_WORKSPACES_ALLOW_ALT,
  DEPCRUISE_API_PRODUCT_WORKSPACES_ALT,
  DEPCRUISE_API_PLUGIN_REGISTRY_FROM_PATH_NOT,
  DEPCRUISE_API_PLUGIN_REGISTRY_PRODUCT_PATH_NOT_FRAGMENTS,
  PRODUCT_WORKSPACE_ID_ALT,
  PORTAL_REGISTER_GENERATED_RELS,
};
`;
}

/** @param {string} value */
function escapeRegexLiteral(value) {
  return value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}
